test('exact plan removal preserves all entities and shared plans; backup restores it',()=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'robos-plan-lifecycle-'));
 const ws=new GraphWorkspace(dir);ws.apply(ws.propose({mode:'replace',document:ws.empty('Lifecycle test')}));
 ws.apply(proposePlan(dir,input(),fetchIssue));
 ws.apply(proposePlan(dir,{...input(),id:'shared'},fetchIssue));
 const backup=exportPlan(dir,'delivery'), before=ws.read(), beforeHash=hash(before);
 assert.throws(()=>proposeRemovePlan(dir,'2'),/exact/);
 assert.throws(()=>proposeRemovePlan(dir,url(2)),/exact/);
 const proposal=proposeRemovePlan(dir,backup.graphId);
 assert.equal(proposal.validation.conforms,true);assert.equal(hash(ws.read()),beforeHash);
 ws.apply(proposal);
 assert.deepEqual(plans(dir).map(p=>p.id),['shared']);
 const expected=structuredClone(before);delete expected['robos:nodes'].find(n=>n['@id']===backup.graphId)['robos:planJson'];
 assert.deepEqual(ws.read()['robos:nodes'],expected['robos:nodes']);
 assert.equal(viewPlan(dir,'2',undefined,fetchIssue).plans[0].id,'shared');
 assert.throws(()=>proposeRemovePlan(dir,backup.graphId),/exact/);
 ws.apply(proposePlan(dir,backup,fetchIssue));assert.equal(plans(dir).length,2);
 assert.equal(viewPlan(dir,backup.graphId).plans[0].id,'delivery');
 const stale=proposeRemovePlan(dir,backup.graphId);
 ws.apply(proposePlan(dir,{...backup,summary:'Revised'},fetchIssue));
 assert.throws(()=>ws.apply(stale),/Stale/);
});
