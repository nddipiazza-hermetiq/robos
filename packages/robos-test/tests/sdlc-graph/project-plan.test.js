const {validatePlan,proposePlan,viewPlan,plans,issueIdentity,exportPlan,proposeRemovePlan}=require('../../../task-planner/lib/project-plan');
const capabilities=require('../../../robos-graph/lib/inspector-capabilities');
const url=n=>`https://github.com/example/tracker/issues/${n}`;
const input=()=>({version:1,id:'delivery',namespace:'example',name:'Delivery plan',summary:'Ship the feature',design:'Review then implement',verification:'Real application proof',owners:['Owner'],repository:'example/tracker',status:'review-required',source:{repository:'example/plans',path:'delivery.json'},items:[{url:url(1),type:'Feature',delivery:'Design and delivery'},{url:url(2),type:'Task',parent:url(1),delivery:'Implement the approved design'}]});
